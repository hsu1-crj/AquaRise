def _select_response(message: str) -> str:
    """按关键字匹配选择回复"""
    for keywords, text in MOCK_RESPONSES:
        if any(kw in message for kw in keywords):
            return text
    return DEFAULT_RESPONSE


async def generate_chat_stream(message: str) -> AsyncGenerator[str, None]:
    """
    模拟 LLM 流式回复：逐字符产出。
    yield 出的片段会被 SSE 接口包装为 data: <chunk>
    """
    response = _select_response(message)
    for char in response:
        await asyncio.sleep(0.03)  # 模拟流式生成节奏
        yield char
